package com.mihaicristiancondrea.android.libs.apptoolkit.core.ui.views.modifiers

import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.focus.onFocusChanged
import com.mihaicristiancondrea.android.libs.apptoolkit.core.ui.models.analytics.Ga4EventData
import com.mihaicristiancondrea.android.libs.apptoolkit.core.ui.views.analytics.LocalTelemetry
import com.mihaicristiancondrea.android.libs.apptoolkit.core.ui.views.analytics.logGa4Event

/** Logs [ga4Event] the moment the element takes focus, and not again until focus comes back. */
@Composable
internal fun Modifier.logFocusGain(
    ga4Event: Ga4EventData?,
): Modifier {
    val telemetry = LocalTelemetry.current
    var focused: Boolean by remember { mutableStateOf(value = false) }
    return onFocusChanged { state ->
        if (state.isFocused && !focused) telemetry.logGa4Event(ga4Event = ga4Event)
        focused = state.isFocused
    }
}

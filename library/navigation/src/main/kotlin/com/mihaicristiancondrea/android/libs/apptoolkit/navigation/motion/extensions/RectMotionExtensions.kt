package com.mihaicristiancondrea.android.libs.apptoolkit.navigation.motion.extensions

import androidx.compose.ui.geometry.Rect

/** Returns this rectangle scaled by [scale] around its center. */
internal fun Rect.scaleCentered(scale: Float): Rect {
    val halfWidth = width * scale / 2f
    val halfHeight = height * scale / 2f
    return Rect(
        left = center.x - halfWidth,
        top = center.y - halfHeight,
        right = center.x + halfWidth,
        bottom = center.y + halfHeight,
    )
}
